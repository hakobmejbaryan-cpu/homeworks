Travelers = int(input("Enter the number of travelers: "))
Nights = int(input("Enter the number of nights: "))
AccommodationCost = float(input("Enter the cost of accommodation per night: "))
TotalAccommodationCost = Nights * AccommodationCost
TransportationCost = float(input("Enter the cost of transportation: "))
FoodCost = float(input("Enter the cost of food per traveler per day: "))
print("Travelers:", Travelers)
print("Nights:", Nights)
print("Transportation cost:", TransportationCost)
print("food cost per traveler per day:", FoodCost)
print("Total accommodation cost for", Nights, "nights is:", TotalAccommodationCost)
print("Total transportation cost is:", TransportationCost)
print("Total food cost for", Travelers, "travelers for", Nights, "nights is:", FoodCost * Travelers * Nights)
print("Total trip cost is:", TotalAccommodationCost + TransportationCost + (FoodCost * Travelers * Nights))
print("Cost per traveler is:", (TotalAccommodationCost + TransportationCost + (FoodCost * Travelers * Nights)) / Travelers)
